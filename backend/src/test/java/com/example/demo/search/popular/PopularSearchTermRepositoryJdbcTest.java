package com.example.demo.search.popular;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;

import java.time.Instant;
import java.time.LocalDate;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

class PopularSearchTermRepositoryJdbcTest {

    private static final LocalDate TODAY = LocalDate.of(2026, 11, 24);
    private static final Instant NOW = Instant.parse("2026-11-24T04:05:06Z");

    private EmbeddedDatabase database;
    private JdbcTemplate jdbc;
    private PopularSearchTermRepository repository;

    @BeforeEach
    void createTable() {
        database = new EmbeddedDatabaseBuilder().generateUniqueName(true)
                .setType(EmbeddedDatabaseType.H2).build();
        jdbc = new JdbcTemplate(database);
        repository = new PopularSearchTermRepository(jdbc);
        jdbc.execute("""
                CREATE TABLE popular_search_terms (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    search_type VARCHAR(16) NOT NULL,
                    account_id BIGINT NOT NULL,
                    keyword VARCHAR(128) NOT NULL,
                    normalized_keyword VARCHAR(128) NOT NULL,
                    search_day DATE NOT NULL,
                    created_at TIMESTAMP NOT NULL,
                    CONSTRAINT uq_popular_search_terms_account_day
                        UNIQUE (account_id, search_type, normalized_keyword, search_day)
                )
                """);
    }

    @AfterEach
    void closeDatabase() {
        database.shutdown();
    }

    @Test
    void deduplicatesAnAccountAndAppliesTypeAndFiveSearcherThreshold() {
        for (long accountId = 1; accountId <= 5; accountId++) {
            assertThat(repository.insertIfAbsent(accountId, PopularSearchType.THREADS,
                    "Spring Boot", "spring boot", TODAY, NOW)).isEqualTo(1);
        }
        assertThat(repository.insertIfAbsent(1L, PopularSearchType.THREADS,
                "Spring Boot", "spring boot", TODAY, NOW)).isZero();
        for (long accountId = 1; accountId <= 4; accountId++) {
            repository.insertIfAbsent(accountId, PopularSearchType.THREADS,
                    "Java", "java", TODAY, NOW);
        }
        for (long accountId = 1; accountId <= 5; accountId++) {
            repository.insertIfAbsent(accountId, PopularSearchType.THREADS,
                    "Alpha", "alpha", TODAY, NOW);
        }
        for (long accountId = 1; accountId <= 6; accountId++) {
            repository.insertIfAbsent(accountId, PopularSearchType.THREADS,
                    "Beta", "beta", TODAY, NOW);
        }
        repository.insertIfAbsent(99L, PopularSearchType.USERS,
                "Spring Boot", "spring boot", TODAY, NOW);
        repository.insertIfAbsent(100L, PopularSearchType.THREADS,
                "Spring Boot", "spring boot", TODAY.minusDays(7), NOW);

        assertThat(repository.findPopular(PopularSearchType.THREADS,
                TODAY.minusDays(6), TODAY, 10, 5))
                .containsExactly("Beta", "Alpha", "Spring Boot");
    }

    @Test
    void expiryDeletesOnlyExpiredRowsAndHonorsBatchBound() {
        repository.insertIfAbsent(1L, PopularSearchType.THREADS,
                "old one", "old one", TODAY.minusDays(2), NOW);
        repository.insertIfAbsent(2L, PopularSearchType.THREADS,
                "old two", "old two", TODAY.minusDays(2), NOW);
        repository.insertIfAbsent(3L, PopularSearchType.THREADS,
                "current", "current", TODAY, NOW);

        assertThat(repository.deleteExpiredBefore(TODAY.minusDays(1), 1)).isEqualTo(1);
        assertThat(jdbc.queryForObject(
                "SELECT COUNT(*) FROM popular_search_terms WHERE search_day < ?", Integer.class,
                java.sql.Date.valueOf(TODAY.minusDays(1)))).isEqualTo(1);
        assertThat(jdbc.queryForObject(
                "SELECT COUNT(*) FROM popular_search_terms WHERE search_day = ?", Integer.class,
                java.sql.Date.valueOf(TODAY))).isEqualTo(1);
    }
}
